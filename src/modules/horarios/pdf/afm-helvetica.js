// cabe en una columna a 11 pt hay que saber cuánto mide. Sin esta tabla habría que fijar
// un ancho por carácter, que es lo que produce esos PDF con nombres cortados o con huecos
// enormes. Con ella se puede medir de verdad y ajustar.
//
// Un error de una milésima aquí no rompe nada: el lector de PDF usa las métricas reales de
// la fuente. Lo único que cambia es lo conservador que sea nuestro cálculo.

const R = (desde, hasta, ancho, tabla) => { for (let i = desde; i <= hasta; i++) tabla[i] = ancho; };

function construir(pares) {
  const t = new Array(256).fill(556);   // valor razonable para lo que no esté tabulado
  for (const [cod, ancho] of pares) t[cod] = ancho;
  return t;
}

