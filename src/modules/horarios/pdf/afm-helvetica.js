export const ANCHURAS = { normal: HELV, negrita: HELV_B };

// Ancho de un texto (ya en códigos WinAnsi) a un tamaño dado, en puntos.
export function anchoDe(codigos, tam, fuente = "normal") {
  const tabla = ANCHURAS[fuente] || HELV;
  let total = 0;
  for (const c of codigos) total += tabla[c] || 556;
  return (total * tam) / 1000;
}
